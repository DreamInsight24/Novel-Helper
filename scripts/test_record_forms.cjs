const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');const vm=require('node:vm');
const context=vm.createContext({i18n:{t:key=>key},window:{addEventListener(){}}});
for(const file of ['core','records'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../app/novelhelper/web/'+file+'.js'),'utf8'),context);
const run=code=>vm.runInContext(code,context);
run(`state.db={schema:{characters:{elements:[{key:'Large template',children:[{key:'Detail'}]}]}},equipment:{slots:[]}};
 globalThis.rec=newRecord(defFor('characters'));`);
assert.equal(run('rec.elements.length'),0,'New records must not inherit a large form');
run(`globalThis.faction={members:['a',{id:'a',note:'Legacy role'},{id:'b',note:'Officer'}]};
 updateFactionMembership(faction,'a','Guard');`);
assert.equal(run('faction.members.join(",")'),'a,b');
assert.equal(run('faction.member_roles.a'),'Guard');
assert.equal(run('faction.member_roles.b'),'Officer','Normalizing a legacy relation preserves other roles');
run(`updateFactionMembership(faction,'a','Guard');`);
assert.equal(run('faction.members.length'),2,'Adding the same relation must not duplicate it');
run(`updateFactionMembership(faction,'a','',true);`);
assert.equal(run('faction.members.join(",")'),'b');
assert.equal(run('faction.member_roles.a'),undefined);
run(`h=(tag,props,...children)=>({tag,props:props||{},value:props?.value||'',children:children.flat(Infinity).filter(Boolean),focus(){},classList:{add(){}}});
 modal=(title,body,buttons)=>{globalThis.dialog={title,body,buttons};return {close(){},dlg:{classList:{add(){}}}};};
 globalThis.walk=node=>[node,...node.children.filter(child=>typeof child==='object').flatMap(walk)];
 globalThis.created=[];toast=()=>{};
 showRecordCreate(defFor('characters'),record=>created.push(record));`);
assert.equal(run('created.length'),0,'Opening create must not persist an unnamed record');
run(`dialog.buttons.find(button=>button.props.text==='common.cancel').props.onclick();`);
assert.equal(run('created.length'),0);
run(`showRecordCreate(defFor('characters'),record=>created.push(record));
 dialog.buttons.find(button=>button.props.text==='records.create').props.onclick();`);
assert.equal(run('created.length'),0,'A name is required');
run(`walk(dialog.body).find(node=>node.props.id==='record-create-name').value='New character';
 walk(dialog.body).find(node=>node.props.id==='record-create-summary').value='Summary';
 walk(dialog.body).find(node=>node.props.id==='record-create-content').value='Description';
 dialog.buttons.find(button=>button.props.text==='records.create').props.onclick();`);
assert.equal(run('created.length'),1);
assert.equal(run('created[0].summary'),'Summary');
assert.equal(run('created[0].content'),'Description');
assert.equal(run('created[0].elements.length'),0);
console.log('PASS: lightweight creation, cancel, required name, prose, canonical memberships, duplicate prevention, and legacy roles');
